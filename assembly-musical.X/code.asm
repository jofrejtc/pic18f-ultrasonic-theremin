LIST P=PIC18F4321 F=INHX32    
    #include <p18f4321.inc>

    CONFIG  OSC=HSPLL ; L'oscil.lador, temps instruccio 1us per tant 4MHz
    CONFIG  PBADEN=DIG ; Volem que el PORTB sigui DIGital
    CONFIG  WDT=OFF    ; Desactivem el Watch Dog TimeR
    CONFIG  MCLRE=ON

    NUM_NOTES EQU 0x0000
    COUNT_5us EQU 0x0001
    ENABLE_SERVO EQU 0x0002
    ENABLE_3s EQU 0x0003
    ENABLE_SPEAKER EQU 0x0004
    ENABLE_DURATION EQU 0x0005
    ENABLE_500ms EQU 0x0006
    SPEAKER EQU 0x0007
    COUNT_SPEAKER EQU 0x0008
    COUNT_LOW_DURATION EQU 0x0009
    COUNT_HIGH_DURATION EQU 0x000A
    COUNT_TRIGGER_LOW_DURATION EQU 0x000B
    COUNT_TRIGGER_HIGH_DURATION EQU 0x000C
    COUNT_NOTE_FINE EQU 0x000D
    NOTA EQU 0x000E
    DURATION EQU 0x000F
    COUNT_LOW_500ms EQU 0x0010
    COUNT_HIGH_500ms EQU 0x0011
    COUNT_SERVO_20ms EQU 0x0012
    COUNT_LOW_3s EQU 0x0013
    COUNT_HIGH_3s EQU 0x0014
    FINE_GRADE EQU 0x0015
    FINE_GRADE_AUX EQU 0x0016
    COUNT_NOTE_FINE_AUX EQU 0x0017
    COUNT_WAIT_GRADE EQU 0x0018
    NUM_NOTES_AUX EQU 0x0019
    COUNT_CM_ULTRASONS EQU 0x001A
    SERVO_05 EQU 0x001B
    END_NOTE EQU 0x001C
    READ_RAM EQU 0x001D
    COUNT_60us EQU 0x001E
    COUNT_ULTRASONS EQU 0x001F
    ENABLE_EMPTY EQU 0x0020
    AUX EQU 0x0021
 
    TABLE EQU 0x0200

    ORG 0x0000
    GOTO MAIN
    ORG 0x0008
    GOTO HIGH_RSI
    ORG 0x0018
    RETFIE FAST
    
    ORG TABLE
	DB .0,.180,.90,.60
	DB .45,.36,.30,.25
	DB .22,.20,.18,.16
	DB .15,.13,.12,.12
	DB .11,.10,.10,.9
	DB .9,.8,.8,.7
	DB .7,.6,.0,.0

    HIGH_RSI
	BTFSC INTCON,INT0IF,0 ; Interrupció per flanc de baixada (NewNote)
	CALL NEWNOTE

	BTFSC INTCON,TMR0IF,0 ; Interrupció del Timer0
	CALL TIMER0
    RETFIE FAST
    
    NEWNOTE
	BCF INTCON,INT0IF,0
	MOVFF PORTD,AUX
	
	BSF ENABLE_EMPTY,0,0
	BTFSC AUX,4,0
	BCF ENABLE_EMPTY,0,0
	BTFSC AUX,5,0
	BCF ENABLE_EMPTY,0,0
	
	BTFSC ENABLE_EMPTY,0,0
	BSF AUX,4,0
	
	MOVFF AUX, POSTINC0
	INCF NUM_NOTES,1,0
	BSF LATA,0,0 ; PIN ACK
	CALL WAIT_2ms
	BCF LATA,0,0 ; PIN ACK
    RETURN
    
    WAIT_2ms
	CALL WAIT_5us
	CALL WAIT_5us
	CALL WAIT_5us
	CALL WAIT_5us
    RETURN
    
    WAIT_5us
	MOVLW .227
	MOVWF COUNT_5us,0
	NOP
	NOP
	LOOP_5us
            NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    DECFSZ COUNT_5us,1,0
	    GOTO LOOP_5us
    RETURN
    
    TIMER0
	BCF INTCON,TMR0IF,0 ; Netejar flag
	CALL LOAD_TMR0 ; Recarregar timer
	
	BTFSC ENABLE_3s,0,0
	CALL WAIT_3s
	
	BTFSC ENABLE_500ms,0,0
	CALL WAIT_500ms
	
	BTFSC ENABLE_DURATION,0,0
	CALL WAIT_DURATION
	
	BTFSC ENABLE_SPEAKER,0,0
	CALL SPEAKER_FUNC
	
	BTFSC ENABLE_SERVO,0,0
	CALL WAIT_SERVO
    RETURN
    
    WAIT_SERVO 
	INCF COUNT_SERVO_20ms,1,0
	MOVLW .20
	SUBWF COUNT_SERVO_20ms,0,0
	
	BTFSC STATUS,Z,0
	BCF ENABLE_SERVO,0,0
    RETURN
    
    SPEAKER_FUNC
	INCF COUNT_SPEAKER,1,0
	MOVF SPEAKER,0,0
	SUBWF COUNT_SPEAKER,0,0
	
	BTFSC STATUS,Z,0
	CALL CHANGE_SPEAKER
    RETURN
    
    CHANGE_SPEAKER
	BTG LATB,3,0
	CLRF COUNT_SPEAKER,0
    RETURN
    
    WAIT_DURATION
	INCF COUNT_LOW_DURATION,1,0
	MOVLW .0
	SUBWF COUNT_LOW_DURATION,0,0
	BTFSC STATUS,Z,0
	INCF COUNT_HIGH_DURATION,1,0
	
	MOVF COUNT_TRIGGER_HIGH_DURATION,0,0 ;COMPAREM PART ALTA DE LA DURATION
	SUBWF COUNT_HIGH_DURATION,0,0
	BTFSS STATUS,Z,0 
	RETURN ; EN CAS DE ERRONI RETURN
	
	MOVF COUNT_TRIGGER_LOW_DURATION,0,0 ;COMPAREM PART BAIXA DE LA DURATION
	SUBWF COUNT_LOW_DURATION,0,0
	BTFSS STATUS,Z,0
	RETURN	; EN CAS DE ERRONI RETURN
	
	; ENCERT DE DURATION
	BSF LATB,1,0
	BCF LATB,2,0
	BCF ENABLE_DURATION,0,0
	INCF COUNT_NOTE_FINE,1,0 ; INCREMENTEM NOTES BÉ
    RETURN
    
    WAIT_500ms
	INCF COUNT_LOW_500ms,1,0
	MOVLW .0
	SUBWF COUNT_LOW_500ms,0,0
	BTFSC STATUS,Z,0
	INCF COUNT_HIGH_500ms,1,0
	
	MOVLW .1
	SUBWF COUNT_HIGH_500ms,0,0
	BTFSS STATUS,Z,0
	RETURN
	
	MOVLW .244
	SUBWF COUNT_LOW_500ms,0,0
	BTFSS STATUS,Z,0
	RETURN
	
	BCF ENABLE_3s,0,0
	BCF ENABLE_500ms,0,0
	BCF LATB,1,0
	BCF LATB,2,0
	
	; START DE DURATION
	BSF ENABLE_DURATION,0,0
	CLRF COUNT_LOW_DURATION,0
	CLRF COUNT_HIGH_DURATION,0
    RETURN
    
    WAIT_3s
	INCF COUNT_LOW_3s,1,0
	MOVLW .0
	SUBWF COUNT_LOW_3s,0,0
	BTFSC STATUS,Z,0
	INCF COUNT_HIGH_3s,1,0
	
	MOVLW .11
	SUBWF COUNT_HIGH_3s,0,0
	BTFSS STATUS,Z,0
	RETURN
	
	MOVLW .368 ; .184 puede ser
	SUBWF COUNT_LOW_3s,0,0
	BTFSS STATUS,Z,0
	RETURN
	
	BCF ENABLE_3s,0,0
	BCF ENABLE_500ms,0,0
	BCF LATB,1,0
	BSF LATB,2,0
    RETURN
    
    INIT_PORTS
	BCF TRISA,0,0 ;ACK
	BCF LATA,0,0
	
	BSF TRISB,0,0 ;NewNote
	
	BCF TRISA,2,0 ;GameScore (SERVO)
	BCF LATA,2,0
	
	BCF TRISA,3,0 ;Length[0]
	BCF LATA,3,0
	BCF TRISA,4,0 ;Length[1]
	BCF LATA,4,0
	
	BCF TRISB,1,0 ;AnswerCorrect
	BCF LATB,1,0
	BCF TRISB,2,0 ;AnswerIncorrect
	BCF LATB,2,0
	
	BCF TRISB,3,0 ;Speaker
	BCF LATB,3,0
	
	CLRF TRISC,0 ;CurrentNote
	SETF LATC,0
	
	SETF TRISD,0 ;  Duration + Note + StartGame [LSB --> MSB]
	
	MOVLW 0x0F
	MOVWF ADCON1,0
	BSF TRISA,1,0 ; Echo
	BCF TRISE,0,0 ; Trigger
	BCF LATE,0,0
    RETURN
    
    INIT_VARS
	CLRF NUM_NOTES,0
	CLRF COUNT_SPEAKER,0
	CLRF COUNT_NOTE_FINE,0
	
	BCF ENABLE_3s,0,0
	BCF ENABLE_500ms,0,0
	BCF ENABLE_DURATION,0,0
	BCF ENABLE_SPEAKER,0,0
	BCF ENABLE_SERVO,0,0
    RETURN
    
    INIT_INTERRUPTS
	BSF INTCON,7,0
	BSF INTCON,6,0

	BCF INTCON,TMR0IF,0
	BCF INTCON,INT0IF,0
	
	BSF INTCON,TMR0IE,0
	BSF INTCON,INT0IE,0
	BCF INTCON2,INTEDG0,0 ; FLANG DE BAIXADA
    RETURN
    
    INIT_BANK
	MOVLW .1
	MOVWF FSR0H,0
	CLRF FSR0L,0
    RETURN
    
    WAIT_FIRST_DURATION
	MOVLW HIGH(.1000)
	MOVWF COUNT_TRIGGER_HIGH_DURATION,0
	MOVLW LOW(.1000)
	MOVWF COUNT_TRIGGER_LOW_DURATION,0
    RETURN
    
    WAIT_SECOND_DURATION
	MOVLW HIGH(.2000)
	MOVWF COUNT_TRIGGER_HIGH_DURATION,0
	MOVLW LOW(.2000)
	MOVWF COUNT_TRIGGER_LOW_DURATION,0
    RETURN
    
    WAIT_THIRD_DURATION
	MOVLW HIGH(.3000)
	MOVWF COUNT_TRIGGER_HIGH_DURATION,0
	MOVLW LOW(.3000)
	MOVWF COUNT_TRIGGER_LOW_DURATION,0
    RETURN
    
    READ_FLASH
	BSF EECON1,EEPGD,0
	BCF EECON1,CFGS,0
	CLRF TBLPTRU,0
	MOVLW HIGH(TABLE)
	MOVWF TBLPTRH,0
	MOVLW LOW(TABLE)
	MOVWF TBLPTRL,0
	
	MOVF NUM_NOTES,0
	ADDWF TBLPTRL,1,0
	INCF TBLPTRL,1,0 ;NO creo que sea
	TBLRD*
	MOVFF TABLAT, FINE_GRADE
    RETURN
    
    STARTGAME_FUNCTION
	CALL READ_FLASH
	CALL INIT_BANK
	
	MOVFF NUM_NOTES, NUM_NOTES_AUX
	MOVLW .0
	SUBWF NUM_NOTES,0,0
	BTFSC STATUS,Z,0
	GOTO LOOP_END 
	
	LOOP_READ
	    MOVFF POSTINC0, READ_RAM
	    
	    MOVF READ_RAM,0
	    ANDLW b'00001111'
	    MOVWF NOTA,0
	    
	    MOVF READ_RAM,0
	    ANDLW b'00110000'
	    MOVWF DURATION,0
	    RRNCF DURATION,1,0
	    RRNCF DURATION,1,0
	    RRNCF DURATION,1,0
	    RRNCF DURATION,1,0
	    
	    MOVLW .1
	    SUBWF DURATION,0
	    BTFSC STATUS,Z,0
	    CALL WAIT_FIRST_DURATION
	    
	    MOVLW .2
	    SUBWF DURATION,0
	    BTFSC STATUS,Z,0
	    CALL WAIT_SECOND_DURATION
	    
	    MOVLW .3
	    SUBWF DURATION,0
	    BTFSC STATUS,Z,0
	    CALL WAIT_THIRD_DURATION
	    
	    CALL SHOW_NOTEDURATION
	    
	    BSF ENABLE_3s,0,0
	    
	    CLRF COUNT_LOW_3s,0
	    CLRF COUNT_HIGH_3s,0
	    
	    LOOP_GAME
		CLRF COUNT_SERVO_20ms,0
		BSF ENABLE_SERVO,0,0
		CALL SERVO
		CALL ULTRASONS
		
		LOOP_SERVO
		    BTFSC ENABLE_SERVO,0,0
		    GOTO LOOP_SERVO
		
		BTFSC ENABLE_3s,0,0
		GOTO LOOP_GAME
		
		BTFSC ENABLE_DURATION,0,0
		GOTO LOOP_GAME
		
		DECFSZ NUM_NOTES_AUX,1,0
		GOTO LOOP_READ
		
		BCF LATB,3,0
		BCF ENABLE_SPEAKER,0,0
		
		LOOP_END
		    MOVLW 0xFE
		    MOVWF LATC,0
		    BCF LATA,4,0
		    BCF LATA,3,0
		    
		    LOOP_END_SERVO
			CLRF COUNT_SERVO_20ms,0
			BSF ENABLE_SERVO,0,0
			CALL SERVO
			LOOP_SERVO_FINAL
			    BTFSC ENABLE_SERVO,0,0
			    GOTO LOOP_SERVO_FINAL
		    GOTO LOOP_END_SERVO
    RETURN
    
    SERVO
	BSF LATA,2,0
	CALL SERVO_RUTINE
	BCF LATA,2,0
    RETURN
    
    SERVO_RUTINE
	CALL WAIT_SERVO_05ms
	MOVFF COUNT_NOTE_FINE, COUNT_NOTE_FINE_AUX
	MOVLW .0
	SUBWF COUNT_NOTE_FINE_AUX,0,0
	BTFSS STATUS,Z,0
	CALL WAIT_GRADE_SERVO
    RETURN
    
    WAIT_GRADE_SERVO
	LOOP_NOTE_FINE_SERVO
	    CALL WAIT_GRADE_NOTE_FINE
	    DECFSZ COUNT_NOTE_FINE_AUX,1,0
	    GOTO LOOP_NOTE_FINE_SERVO
    RETURN
    
    WAIT_GRADE_NOTE_FINE
	MOVFF FINE_GRADE, FINE_GRADE_AUX
	LOOP_GRADE_FOR_NOTE_FINE
	    CALL WAIT_GRADE ; 1 GRAU = 11us ---> (2,5ms - 0,5ms)/180 = 11us
	    DECFSZ FINE_GRADE_AUX,1,0
	    GOTO LOOP_GRADE_FOR_NOTE_FINE
    RETURN
    
    WAIT_GRADE
	MOVLW .35
	MOVWF COUNT_WAIT_GRADE,0
	LOOP_WAIT_GRADE
	    DECFSZ COUNT_WAIT_GRADE,1,0
	    GOTO LOOP_WAIT_GRADE
	NOP
	NOP
    RETURN
    
    WAIT_SERVO_05ms
	MOVLW .227
	MOVWF SERVO_05,0
	LOOP_WAIT_SERVO_05ms
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    NOP
	    DECFSZ SERVO_05,1,0
	    GOTO LOOP_WAIT_SERVO_05ms
    RETURN
    
    ULTRASONS
	CALL WAIT_ULTRASONS_10us
	LOOP_WAIT_ECHO
	    BTFSS ENABLE_SERVO,0,0
	    RETURN
	    BTFSS PORTA,1,0
	    GOTO LOOP_WAIT_ECHO
	CLRF COUNT_CM_ULTRASONS,0
	LOOP_CM_COUNT
	    CALL WAIT_60us
	    INCF COUNT_CM_ULTRASONS,1,0
	    BTFSC PORTA,1,0
	    GOTO LOOP_CM_COUNT
	    
	CALL NOTE_ULTRASONS
	
	BSF ENABLE_EMPTY,1,0
	
	BTFSC ENABLE_DURATION,0,0
	BCF ENABLE_EMPTY,1,0
	
	BTFSC ENABLE_3s,0,0
	BCF ENABLE_EMPTY,1,0
	
	BTFSC ENABLE_EMPTY,1,0
	RETURN
	
	CALL MANAGE_NOTE
    RETURN
    
    MANAGE_NOTE
	MOVF END_NOTE,0,0
	SUBWF NOTA,0,0
	BTFSC STATUS,Z,0
	CALL COINCIDANCE
	
	MOVF END_NOTE,0,0
	SUBWF NOTA,0,0
	BTFSS STATUS,Z,0
	CALL NO_COINCIDANCE
    RETURN
    
    COINCIDANCE
	BTFSC ENABLE_DURATION,0,0
	RETURN
	BTFSC ENABLE_500ms,0,0
	RETURN
	BSF ENABLE_500ms,0,0
	CLRF COUNT_LOW_500ms,0
	CLRF COUNT_HIGH_500ms,0
    RETURN
    
    NO_COINCIDANCE
	BCF ENABLE_500ms,0,0
	BTFSC ENABLE_DURATION,0,0
	CALL INCORRECT_NOTE 
    RETURN
    
    INCORRECT_NOTE
	BCF ENABLE_DURATION,0,0
	BSF LATB,2,0
	BCF LATB,1,0 
    RETURN
    
    NOTE_ULTRASONS
	MOVLW .0
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	CALL ZERO_NOTE
	
	MOVLW .10
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	CALL ONE_NOTE
	
	MOVLW .20
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	CALL TWO_NOTE
	
	MOVLW .30
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	CALL THREE_NOTE
	
	MOVLW .40
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	CALL FOUR_NOTE
	
	MOVLW .50
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	CALL FIVE_NOTE
	
	MOVLW .60
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	CALL SIX_NOTE

	MOVLW .70
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	CALL NO_NOTE
    RETURN
    
    NO_NOTE
	MOVLW .8
	MOVWF END_NOTE,0
	BCF ENABLE_SPEAKER,0,0
    RETURN
    
    SIX_NOTE
	MOVLW .70
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	RETURN

	MOVLW .6
	MOVWF END_NOTE,0
	BSF ENABLE_SPEAKER,0,0
	MOVLW .1
	MOVWF SPEAKER,0
    RETURN
    
    FIVE_NOTE
	MOVLW .60
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	RETURN

	MOVLW .5
	MOVWF END_NOTE,0
	BSF ENABLE_SPEAKER,0,0
	MOVLW .2
	MOVWF SPEAKER,0
    RETURN
    
    FOUR_NOTE
	MOVLW .50
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	RETURN

	MOVLW .4
	MOVWF END_NOTE,0
	BSF ENABLE_SPEAKER,0,0
	MOVLW .3
	MOVWF SPEAKER,0
    RETURN
    
    THREE_NOTE
	MOVLW .40
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	RETURN
	
	MOVLW .3
	MOVWF END_NOTE,0
	BSF ENABLE_SPEAKER,0,0
	MOVLW .4
	MOVWF SPEAKER,0
    RETURN
    
    TWO_NOTE
	MOVLW .30
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	RETURN

	MOVLW .2
	MOVWF END_NOTE,0
	BSF ENABLE_SPEAKER,0,0
	MOVLW .5
	MOVWF SPEAKER,0
    RETURN
    
    ONE_NOTE
	MOVLW .20
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	RETURN
	
	MOVLW .1
	MOVWF END_NOTE,0
	BSF ENABLE_SPEAKER,0,0
	MOVLW .6
	MOVWF SPEAKER,0
    RETURN
    
    ZERO_NOTE
	MOVLW .10
	SUBWF COUNT_CM_ULTRASONS,0,0
	BTFSC STATUS,C,0
	RETURN
	
	MOVLW .0
	MOVWF END_NOTE,0
	BSF ENABLE_SPEAKER,0,0
	MOVLW .7
	MOVWF SPEAKER,0
    RETURN
    
    WAIT_60us
	MOVLW .198
	MOVWF COUNT_60us,0
	LOOP_WAIT_60us
	    DECFSZ COUNT_60us,1,0
	    GOTO LOOP_WAIT_60us
    RETURN
    
    WAIT_ULTRASONS_10us
	BSF LATE,0,0
	CALL WAIT_10us
	BCF LATE,0,0
    RETURN
    
    WAIT_10us
	MOVLW .31
	MOVWF COUNT_ULTRASONS,0
	LOOP_WAIT_10us
	    DECFSZ COUNT_ULTRASONS,1,0
	    GOTO LOOP_WAIT_10us
	NOP
    RETURN
    
    SHOW_NOTEDURATION
	MOVLW .0
	SUBWF NOTA,0,0
	BTFSC STATUS,Z,0
	CALL ZERO_CURRENT_NOTE

	MOVLW .1
	SUBWF NOTA,0,0
	BTFSC STATUS,Z,0
	CALL ONE_CURRENT_NOTE

	MOVLW .2
	SUBWF NOTA,0,0
	BTFSC STATUS,Z,0
	CALL TWO_CURRENT_NOTE

	MOVLW .3
	SUBWF NOTA,0,0
	BTFSC STATUS,Z,0
	CALL THREE_CURRENT_NOTE

	MOVLW .4
	SUBWF NOTA,0,0
	BTFSC STATUS,Z,0
	CALL FOUR_CURRENT_NOTE

	MOVLW .5
	SUBWF NOTA,0,0
	BTFSC STATUS,Z,0
	CALL FIVE_CURRENT_NOTE

	MOVLW .6
	SUBWF NOTA,0,0
	BTFSC STATUS,Z,0
	CALL SIX_CURRENT_NOTE
	
	MOVLW .1
	SUBWF DURATION,0,0
	BTFSC STATUS,Z,0
	CALL FIRST_LENGTH
	
	MOVLW .2
	SUBWF DURATION,0,0
	BTFSC STATUS,Z,0
	CALL SECOND_LENGTH
	
	MOVLW .3
	SUBWF DURATION,0,0
	BTFSC STATUS,Z,0
	CALL THIRD_LENGTH
    RETURN
    
    ZERO_CURRENT_NOTE
	MOVLW 0x01 ; Valor de 0 --> 0x7D
	MOVWF LATC,0
    RETURN
    
    ONE_CURRENT_NOTE
	MOVLW 0x2F ; Valor de 1 --> 0x30
	MOVWF LATC,0
    RETURN
    
    TWO_CURRENT_NOTE
	MOVLW 0x12 ; Valor de 2 --> 0x6E
	MOVWF LATC,0
    RETURN
    
    THREE_CURRENT_NOTE
	MOVLW 0x06 ; Valor de 3 --> 0x7A
	MOVWF LATC,0
    RETURN
    
    FOUR_CURRENT_NOTE
	MOVLW 0x2C ; Valor de 4 --> 0x33
	MOVWF LATC,0
    RETURN
    
    FIVE_CURRENT_NOTE
	MOVLW 0x44 ; Valor de 5 --> 0x5B
	MOVWF LATC,0
    RETURN
    
    SIX_CURRENT_NOTE
	MOVLW 0x40 ; Valor de 6 --> 0x5F
	MOVWF LATC,0
    RETURN
    
    FIRST_LENGTH
	BSF LATA,3,0
	BCF LATA,4,0
    RETURN
    
    SECOND_LENGTH
	BCF LATA,3,0
	BSF LATA,4,0
    RETURN
    
    THIRD_LENGTH
	BSF LATA,3,0
	BSF LATA,4,0
    RETURN

    INIT_TMR0
	MOVLW b'10011000' ; VALOR
	MOVWF T0CON,0
    RETURN

    LOAD_TMR0
	; FEM LA CÂRREGA DEL TIMER
	MOVLW HIGH (.55536) ; VALOR
	MOVWF TMR0H,0
	MOVLW LOW (.55536) ; VALOR
	MOVWF TMR0L,0
    RETURN

    MAIN
	CALL INIT_PORTS
	CALL INIT_INTERRUPTS
	CALL INIT_VARS
	CALL INIT_BANK
	CALL INIT_TMR0
	CALL LOAD_TMR0

	LOOP
	   BTFSC PORTD,6,0 ; STARTGAME
	   CALL STARTGAME_FUNCTION
	   GOTO LOOP
    END